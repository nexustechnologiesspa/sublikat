const expectedProductCounts = [7, 3, 5, 2, 3];
const isUnique = (values) => new Set(values).size === values.length;

const assertCatalogData = () => {
  const productsByCategory = catalogCategories.map((category) =>
    catalogProducts.filter((product) => product.category === category.dataCategoria)
  );
  const orderedProducts = productsByCategory.flat();
  const polerones = catalogProducts.find(
    (product) => product.dataOdId === 'producto-polerones'
  );

  if (catalogCategories.length !== 5) {
    throw new Error('El catálogo debe tener exactamente cinco categorías.');
  }
  if (catalogProducts.length !== 20) {
    throw new Error('El catálogo debe tener exactamente veinte productos.');
  }
  if (
    !isUnique(catalogCategories.map((category) => category.dataCategoria)) ||
    !isUnique(catalogCategories.map((category) => category.tabId)) ||
    !isUnique(catalogCategories.map((category) => category.panelId)) ||
    !isUnique([
      ...catalogCategories.map((category) => category.tabId),
      ...catalogCategories.map((category) => category.panelId)
    ])
  ) {
    throw new Error('Los identificadores de categorías, pestañas y paneles deben ser únicos.');
  }
  if (
    !isUnique(catalogProducts.map((product) => product.dataOdId)) ||
    !isUnique(catalogProducts.map((product) => product.name)) ||
    !isUnique(catalogProducts.map((product) => product.dataProducto)) ||
    !isUnique(catalogProducts.map((product) => product.svgKey))
  ) {
    throw new Error('Los identificadores, productos y claves SVG deben ser únicos.');
  }

  catalogCategories.forEach((category, index) => {
    const products = productsByCategory[index];
    if (
      category.order !== index + 1 ||
      category.productCount !== expectedProductCounts[index] ||
      products.length !== expectedProductCounts[index]
    ) {
      throw new Error(`Orden o conteo incorrecto para la categoría ${category.dataCategoria}.`);
    }
    products.forEach((product, productIndex) => {
      if (product.orderInCategory !== productIndex + 1) {
        throw new Error(`Orden incorrecto dentro de ${category.dataCategoria}.`);
      }
    });
  });

  if (
    orderedProducts.some((product, index) => product !== catalogProducts[index]) ||
    catalogProducts.some(
      (product, index) =>
        product.order !== index + 1 ||
        !catalogCategories.some((category) => category.dataCategoria === product.category) ||
        !product.svgKey ||
        product.dataProducto !== product.name
    )
  ) {
    throw new Error('Los productos deben conservar orden y pertenecer a una categoría existente.');
  }

  if (
    !polerones ||
    polerones.hasOdReveal ||
    catalogProducts.some(
      (product) => product.dataOdId !== 'producto-polerones' && !product.hasOdReveal
    )
  ) {
    throw new Error('La excepción de od-reveal de Polerones debe conservarse.');
  }
};

assertCatalogData();
